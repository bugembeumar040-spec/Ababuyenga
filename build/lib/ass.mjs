function ev(layer, start, end, styleName, text) {
  return `Dialogue: ${layer},${ts(start)},${ts(end)},${styleName},,0,0,0,,${text}`;
}

/** Apply the accent colour to whole words listed in the scene's accentWords. */
function colourise(line, accentSet, fillColour, accentColour) {
  if (!accentSet.size) return esc(line);
  return line
    .split(' ')
    .map((w) => (accentSet.has(norm(w))
      ? `{\\c${accentColour}}${esc(w)}{\\c${fillColour}}`
      : esc(w)))
    .join(' ');
}

export function captionEvents(bursts, scene, style, W, H) {
  const font = loadFont(style, 'display');
  const c = style.caption;
  const maxWidth = W - 2 * c.safeMarginX;
  const bandY = (scene.captionY ?? c.bandY) * H;
  const fillColour = col(style.colour.captionFill);
  const accentColour = col(style.colour.accent);
  const accentSet = new Set((scene.accentWords || []).map(norm));

  const events = [];
  const boxes = [];
  for (const b of bursts) {
    // Captions hold one constant size — the reference never resizes a caption to
    // fill the line. Only an overlong burst steps down, and only far enough to fit.
    const { size, lines } = fit(font, b.text, {
      maxWidth,
      minSize: c.minSize,
      maxSize: c.maxSize,
      maxLines: c.maxLines,
    });
    const step = lineStep(font, size, c.lineSpacing);
    const top = bandY - ((lines.length - 1) / 2) * step;
    lines.forEach((line, i) => {
      const y = Math.round(top + i * step);
      const body = colourise(line, accentSet, fillColour, accentColour);
      events.push({
        start: b.start,
        end: b.end,
        line: ev(2, b.start, b.end, 'Caption', `{\\an5\\pos(${Math.round(W / 2)},${y})\\fs${size}\\bord${c.outline}\\shad${c.shadowDepth}}${body}`),
      });
      boxes.push({
        kind: 'caption',
        scene: scene.id,
        start: b.start,
        end: b.end,
        text: line,
        size,
        width: measure(font, line, size),
        top: y - capHeight(font, size) / 2 - c.outline,
        bottom: y + capHeight(font, size) / 2 + c.outline,
      });
    });
  }
  return { events, boxes };
}

/**
 * Height in px of the tallest caption this scene will show.
 *
 * Reserving a flat guess over-claims space: a one-line burst needs about half
 * what a two-line burst does, and over-claiming is what pushes captions off
 * otherwise-usable headroom and down onto the subject.
 */
export function captionBlockHeight(bursts, style, W) {
  const font = loadFont(style, 'display');
  const c = style.caption;
  const maxWidth = W - 2 * c.safeMarginX;
  let tallest = 0;
  for (const b of bursts) {
    const { size, lines } = fit(font, b.text, {
      maxWidth, minSize: c.minSize, maxSize: c.maxSize, maxLines: c.maxLines,
    });
    const h = (lines.length - 1) * lineStep(font, size, c.lineSpacing) + capHeight(font, size) + 2 * c.outline;
    if (h > tallest) tallest = h;
  }
  return tallest;
}

export function cardEvents(card, timing, scene, style, W, H) {
  const display = loadFont(style, 'display');
  const body = loadFont(style, 'body');
  const cs = style.card;
  const cx = Math.round(W / 2);
  const bandY = (card.bandY ?? cs.bandY) * H;
  // The pack calls 05/06 a hard cut with no transition; those cards set fade:false.
  const fade = card.fade === false ? '' : `\\fad(${Math.round(cs.fadeIn * 1000)},${Math.round(cs.fadeOut * 1000)})`;
  const { start, end } = timing;
  const events = [];
  const boxes = [];
  const push = (layer, text, styleName = 'Card') => events.push({ start, end, line: ev(layer, start, end, styleName, text) });

  /**
   * Backing plate. The pack wants held type bare on the artwork, and that is
   * what happens wherever the frame has an empty band. Where it does not — half
   * these stills put a figure straight through the middle — the type gets a
   * cream plate with the same thick dark-brown outline every object in the
   * illustration already carries, so it reads as part of the art direction
   * rather than as text dropped on top of a drawing.
   */
  const plate = (x, y, w, h) => {
    if (!card.plate) return;
    const p = cs.plate || { padX: 44, padY: 30, radius: 18, stroke: 5, alpha: '12' };
    push(0, `{\\an7\\pos(0,0)\\c${col(style.colour.captionOutline)}\\1a&H${p.alpha}&\\3c${col(style.colour.captionFill)}\\bord${p.stroke}\\shad0${fade}\\p1}${rounded(
      Math.round(x - p.padX), Math.round(y - p.padY),
      Math.round(w + 2 * p.padX), Math.round(h + 2 * p.padY), p.radius,
    )}{\\p0}`, 'Shape');
  };

  if (card.kind === 'word' || card.kind === 'line') {
    const isWord = card.kind === 'word';
    const spec = isWord ? cs.word : cs.line;
    const maxWidth = W - 2 * cs.safeMarginX;
    const { size, lines } = fit(display, card.text.toUpperCase(), {
      maxWidth,
      minSize: 60,
      maxSize: spec.maxSize,
      maxLines: isWord ? 1 : 2,
      targetWidth: maxWidth * spec.targetWidthRatio,
    });
    const step = lineStep(display, size, 1.0);
    const blockH = (lines.length - 1) * step + capHeight(display, size);
    const top = bandY - ((lines.length - 1) / 2) * step;
    const colour = isWord ? col(style.colour.accent) : col(style.colour.captionFill);
    const blockW = Math.max(...lines.map((l) => measure(display, l, size)));
    plate(cx - blockW / 2, top - capHeight(display, size) / 2, blockW, blockH + capHeight(display, size) * 0.55);
    lines.forEach((line, i) => {
      const y = Math.round(top + i * step);
      push(1, `{\\an5\\pos(${cx},${y})\\fs${size}\\c${colour}\\bord${spec.outline}${fade}}${esc(line)}`);
    });
    // Accent rule under the block — what separates a held card from a caption.
    const ruleW = Math.round(Math.max(...lines.map((l) => measure(display, l, size))) * 0.5);
    const ruleY = Math.round(top + (lines.length - 1) * step + capHeight(display, size) * 0.98);
    push(1, `{\\an7\\pos(0,0)\\c${col(style.colour.rule)}\\bord0\\shad0${fade}\\p1}${rect(cx - ruleW / 2, ruleY, ruleW, 6)}{\\p0}`, 'Shape');
    boxes.push({
      kind: `card:${card.kind}`, scene: scene.id, start, end, text: lines.join(' '), size,
      width: Math.max(...lines.map((l) => measure(display, l, size))),
      top: top - capHeight(display, size) / 2 - spec.outline,
      bottom: ruleY + 6 + spec.outline,
      blockH,
    });
  }

  if (card.kind === 'pill') {
    const p = cs.pill;
    const label = card.label.toUpperCase();
    const value = card.value.toUpperCase();
    const labelW = measure(body, label, p.labelSize) + p.labelSize * 0.06 * (label.length - 1);
    const valueW = measure(display, value, p.valueSize);
    const innerW = Math.max(labelW, valueW);
    const labelCap = capHeight(body, p.labelSize);
    const valueCap = capHeight(display, p.valueSize);
    const innerH = labelCap + p.gap + valueCap;
    const boxW = Math.round(innerW + 2 * p.padX);
    const boxH = Math.round(innerH + 2 * p.padY);
    const x = Math.round(cx - boxW / 2);
    const y = Math.round(bandY - boxH / 2);

    push(0, `{\\an7\\pos(0,0)\\c${col(style.colour.pillFill)}\\3c${col(style.colour.pillStroke)}\\bord${p.stroke}\\shad0${fade}\\p1}${rounded(x, y, boxW, boxH, p.radius)}{\\p0}`, 'Shape');
    push(1, `{\\an5\\pos(${cx},${Math.round(y + p.padY + labelCap / 2)})\\fs${p.labelSize}${fade}}${esc(label)}`, 'PillLabel');
    push(1, `{\\an5\\pos(${cx},${Math.round(y + p.padY + labelCap + p.gap + valueCap / 2)})\\fs${p.valueSize}${fade}}${esc(value)}`, 'PillValue');
    if (card.note) {
      push(1, `{\\an5\\pos(${cx},${Math.round(y + boxH + p.noteSize * 0.95)})\\fs${p.noteSize}${fade}}${esc(card.note.toLowerCase())}`, 'Note');
    }
    boxes.push({
      kind: 'card:pill', scene: scene.id, start, end, text: `${label} ${value}`,
      size: p.valueSize, width: boxW, top: y, bottom: y + boxH + (card.note ? p.noteSize * 1.5 : 0),
    });
  }

  if (card.kind === 'arrow') {
    const a = cs.arrow;
    const size = card.scale === 'large' ? a.largeSize : a.smallSize;
    const label = card.text.toUpperCase();
    const cap = capHeight(display, size);
    const ah = cap * a.heightRatio;
    const aw = ah / a.headRatio * 0.52;
    const labelW = measure(display, label, size);
    const total = aw + a.gap + labelW;
    const ax = cx - total / 2 + aw / 2;
    const tx = cx - total / 2 + aw + a.gap;

    plate(cx - total / 2, bandY - ah / 2, total, ah);
    push(1, `{\\an7\\pos(0,0)\\c${col(style.colour.accent)}\\bord0\\shad0${fade}\\p1}${arrow(ax, bandY, ah, aw, card.direction)}{\\p0}`, 'Shape');
    push(1, `{\\an4\\pos(${Math.round(tx)},${Math.round(bandY)})\\fs${size}\\c${col(style.colour.captionFill)}\\bord${Math.round(size / 18)}${fade}}${esc(label)}`);
    boxes.push({
      kind: 'card:arrow', scene: scene.id, start, end, text: `${card.direction} ${label}`, size,
      width: total, top: bandY - ah / 2, bottom: bandY + ah / 2,
    });
  }

  if (card.kind === 'quote') {
    const q = cs.quote;
    const text = `“${card.text}”`;
    const maxWidth = W - 2 * cs.safeMarginX;
    const { size, lines } = fit(body, text, { maxWidth, minSize: 50, maxSize: q.size, maxLines: 2 });
    const step = lineStep(body, size, 1.14);
    const top = bandY - ((lines.length - 1) / 2) * step;
    const qw = Math.max(...lines.map((l) => measure(body, l, size)));
    plate(cx - qw / 2, top - capHeight(body, size) / 2, qw, (lines.length - 1) * step + capHeight(body, size));
    lines.forEach((l, i) => {
      push(1, `{\\an5\\pos(${cx},${Math.round(top + i * step)})\\fs${size}\\c${col(style.colour.captionFill)}\\bord${q.outline}${fade}}${esc(l)}`, 'Note');
    });
    boxes.push({
      kind: 'card:quote', scene: scene.id, start, end, text, size,
      width: Math.max(...lines.map((l) => measure(body, l, size))),
      top: top - capHeight(body, size) / 2 - q.outline,
      bottom: top + (lines.length - 1) * step + capHeight(body, size) / 2 + q.outline,
    });
  }

  if (card.kind === 'list') {
    const l = cs.list;
    const label = `${card.label.toUpperCase()}:`;
    const items = card.items.map((s) => s.toUpperCase());
    const labelCap = capHeight(display, l.labelSize);
    const itemCap = capHeight(display, l.itemSize);
    const itemStep = lineStep(display, l.itemSize, 1.06);
    const totalH = labelCap + l.gap * 2 + (items.length - 1) * itemStep + itemCap;
    const top = bandY - totalH / 2;

    const listW = Math.max(measure(display, label, l.labelSize), ...items.map((it) => measure(display, it, l.itemSize)));
    plate(cx - listW / 2, top, listW, totalH);
    push(1, `{\\an5\\pos(${cx},${Math.round(top + labelCap / 2)})\\fs${l.labelSize}\\c${col(style.colour.accent)}\\bord${l.outline}${fade}}${esc(label)}`);
    items.forEach((item, i) => {
      const y = Math.round(top + labelCap + l.gap * 2 + i * itemStep + itemCap / 2);
      push(1, `{\\an5\\pos(${cx},${y})\\fs${l.itemSize}\\c${col(style.colour.captionFill)}\\bord${l.outline}${fade}}${esc(item)}`);
    });
    boxes.push({
      kind: 'card:list', scene: scene.id, start, end, text: `${label} ${items.join(' · ')}`, size: l.itemSize,
      width: Math.max(measure(display, label, l.labelSize), ...items.map((it) => measure(display, it, l.itemSize))),
      top, bottom: top + totalH,
    });
  }

  if (card.kind === 'collision') {
    const k = cs.collision;
    const maxWidth = W - 2 * cs.safeMarginX;
    // Fit both halves: the configured sizes are a ceiling, not a promise, and a
    // long phrase like "THIS CHARGES YOUR STILLNESS" overflows the safe area at
    // the nominal weight.
    const smallFit = fit(display, card.small.toUpperCase(), {
      maxWidth, minSize: 48, maxSize: k.smallSize, maxLines: 2,
    });
    const largeFit = fit(display, card.large.toUpperCase(), {
      maxWidth, minSize: 84, maxSize: k.largeSize, maxLines: 2,
    });
    const smallStep = lineStep(display, smallFit.size, 1.04);
    const largeStep = lineStep(display, largeFit.size, 1.04);
    const smallH = (smallFit.lines.length - 1) * smallStep + capHeight(display, smallFit.size);
    const largeH = (largeFit.lines.length - 1) * largeStep + capHeight(display, largeFit.size);
    const totalH = smallH + k.gap + k.ruleThickness + k.gap + largeH;
    const top = bandY - totalH / 2;
    const ruleY = Math.round(top + smallH + k.gap);
    const blockW = Math.max(
      ...smallFit.lines.map((l) => measure(display, l, smallFit.size)),
      ...largeFit.lines.map((l) => measure(display, l, largeFit.size)),
      k.ruleWidth,
    );

    plate(cx - blockW / 2, top, blockW, totalH);
    smallFit.lines.forEach((l, i) => {
      push(1, `{\\an5\\pos(${cx},${Math.round(top + i * smallStep + capHeight(display, smallFit.size) / 2)})\\fs${smallFit.size}\\c${col(style.colour.captionFill)}\\bord5${fade}}${esc(l)}`);
    });
    push(1, `{\\an7\\pos(0,0)\\c${col(style.colour.rule)}\\bord0\\shad0${fade}\\p1}${rect(cx - k.ruleWidth / 2, ruleY, k.ruleWidth, k.ruleThickness)}{\\p0}`, 'Shape');
    largeFit.lines.forEach((l, i) => {
      const y = Math.round(ruleY + k.ruleThickness + k.gap + i * largeStep + capHeight(display, largeFit.size) / 2);
      push(1, `{\\an5\\pos(${cx},${y})\\fs${largeFit.size}\\c${col(style.colour.accent)}\\bord7${fade}}${esc(l)}`);
    });
    boxes.push({
      kind: 'card:collision', scene: scene.id, start, end,
      text: `${card.small} / ${card.large}`, size: largeFit.size,
      width: blockW, top, bottom: top + totalH,
    });
  }

  return { events, boxes };
}

export function assemble(style, W, H, events) {
  const sorted = [...events].sort((a, b) => a.start - b.start || a.end - b.end);
  return `${header(style, W, H)}\n${sorted.map((e) => e.line).join('\n')}\n`;
}

