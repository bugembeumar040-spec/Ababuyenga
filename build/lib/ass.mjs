import { loadFont, measure, capHeight, fit } from './text.mjs';

/** #RRGGBB (or RRGGBB) -> ASS &HBBGGRR. */
export function col(hex) {
  const h = hex.replace('#', '').toUpperCase();
  return `&H${h.slice(4, 6)}${h.slice(2, 4)}${h.slice(0, 2)}&`;
}

export function ts(seconds) {
  const s = Math.max(0, seconds);
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const rest = s - h * 3600 - m * 60;
  const cs = Math.round(rest * 100);
  const sec = Math.floor(cs / 100);
  const frac = cs % 100;
  return `${h}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}.${String(frac).padStart(2, '0')}`;
}

const esc = (t) => t.replace(/\\/g, '').replace(/[{}]/g, '');

const norm = (w) => w.toUpperCase().replace(/[^A-Z0-9£%.]/g, '');

/** Baseline-to-baseline step for stacked all-caps lines, in rendered px. */
function lineStep(font, size, spacing = 1) {
  return capHeight(font, size) * 1.22 * spacing;
}

function rounded(x, y, w, h, r) {
  const x2 = x + w;
  const y2 = y + h;
  const R = Math.min(r, w / 2, h / 2);
  return [
    `m ${x + R} ${y}`,
    `l ${x2 - R} ${y}`,
    `b ${x2} ${y} ${x2} ${y} ${x2} ${y + R}`,
    `l ${x2} ${y2 - R}`,
    `b ${x2} ${y2} ${x2} ${y2} ${x2 - R} ${y2}`,
    `l ${x + R} ${y2}`,
    `b ${x} ${y2} ${x} ${y2} ${x} ${y2 - R}`,
    `l ${x} ${y + R}`,
    `b ${x} ${y} ${x} ${y} ${x + R} ${y}`,
  ].join(' ');
}

function rect(x, y, w, h) {
  return `m ${x} ${y} l ${x + w} ${y} l ${x + w} ${y + h} l ${x} ${y + h}`;
}

/**
 * A drawn arrow, not a font glyph. The pack's "set the arrow rising / falling"
 * is a graphic instruction, and a shape stays on-palette and on-weight with the
 * flat-vector artwork in a way a typeface's ↑ never does.
 */
function arrow(cx, cy, h, w, direction) {
  const s = direction === 'up' ? 1 : -1;
  const tipY = cy - s * (h / 2);
  const shoulderY = cy - s * (h / 2 - w * 0.72);
  const tailY = cy + s * (h / 2);
  const half = w / 2;
  const shaft = w * 0.19;
  return [
    `m ${cx} ${tipY}`,
    `l ${cx + half} ${shoulderY}`,
    `l ${cx + shaft} ${shoulderY}`,
    `l ${cx + shaft} ${tailY}`,
    `l ${cx - shaft} ${tailY}`,
    `l ${cx - shaft} ${shoulderY}`,
    `l ${cx - half} ${shoulderY}`,
  ].join(' ');
}

